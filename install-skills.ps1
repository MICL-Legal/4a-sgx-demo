# 目標契約（放手前的六格）

使用者想把一段工作「放手」交出去自己跑（交給 AI 迴圈，或交辦給人）時，你的工作是：先攔截，再用固定順序把這份委任填成六格，最後輸出一段可以直接執行／交辦的契約。

## 先攔截（最重要，先做這一步）
先判斷「做完了沒」是事實，還是使用者的價值判斷。如果需要價值判斷——不可逆的人事處理、對外具法律效力的動作（公文送出、文件簽署、重大訊息揭露）、終止狀態需要對方點頭才成立、探索性研究——不要幫他做成自動迴圈。告訴他：這類事情的停止點永遠是「準備好，等你按」，你只幫他把工作準備到「等人核准」那一步。迴圈只能驗證事實，不能替人判斷對錯。

## 鐵律
- 六格全部填完才算能放手；缺一格就是還沒準備好。
- 每一格用同一個標準檢驗：讓一個完全沒參與的人，只看這格文字，能不能判斷「做完了沒」？不能＝願望，不是條件，重寫。
- 【證據】要寫成「要主動貼出什麼實際輸出」，不是「宣稱通過」。
- 【停止點】永遠放在不可逆動作（刪除／送出／合併／簽署）的前一格。
- 一次問一格，附上建議答案讓對方好反應，決定權在對方。

## 固定順序（六格）
1. 終止狀態：做完長什麼樣？用第三方看得出來的事實描述（不是「做好」「100% confident」）。
2. 證據：你要主動秀出什麼，我才認定完成？（貼實際輸出／截圖／數字，不是說「通過了」）
3. 邊界：哪些東西一根毛都不能動？
4. 上限：回合／時間／成本，任一達標即停。
5. 停止點：做到哪一步交還給人？（放在刪除／送出／合併等不可逆動作的前一格）
6. 未達成：做不到時輸出什麼？（列出卡在哪、為什麼，禁止假裝成功）

## 收尾
把六格組成一段可以直接貼進 /goal（或直接丟給同事）的委任文字。再提醒一次：【上限】和【邊界】一定要寫死——無人看管時，這是唯一的煞車。
'@

