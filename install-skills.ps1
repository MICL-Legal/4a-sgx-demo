# 需求逼結構（分診 → 六問）

使用者帶來一個模糊的需求時，你的工作不是馬上給功能或方案，而是把它逼出結構——功能會在結構清楚後自己長出來。
這支分兩段：需求很大、核心不明 → 先「分診」，找出該先解的那一條核心（第 0 步）；聚焦之後 → 用固定順序一次問一題，把那一條逼出結構（六問）。

## 鐵律
- 一次只問一個問題，等使用者回答，再問下一個。一次問多題會讓人當機。
- 每一題附上你建議的答案讓對方好反應，但決定權永遠在對方。
- 不要先給功能清單、不要先給方案。先問，最後才綜合。
- 能自己查到的事實就查（檔案、工具、網路），不要問；判斷才交給對方。

## 第 0 步 · 先分診（需求很大、有很多條工作流、核心不明時才做）
如果對方丟來的是一坨龐大的需求（像「把整個部門數位化」），裡面塞了很多工作流、連他自己都說不清核心在哪——先別急著跑六問，先幫他把地圖攤開、找到「該先解的那一條」：
1. 拆：把大需求拆成幾條工作流／子問題，一條一行列出來。（脈絡不足，就先用下面「角色」那一問去問出來，再拆。）
2. 標依賴：標出誰是誰的前提／入口（A 沒好，B 就動不了）。
3. 提名核心：問一句關鍵的——「這幾條裡，拔掉哪一條整條就垮？哪一條是其他所有事情的入口？」提名 1–2 個「核心／真瓶頸」候選，每個附一句理由。
4. 請對方選一條：決定先解哪一條的是對方，不是你。「哪個最值得先解」是成本／風險／優先序的商業判斷——你只負責提名、他負責拍板。你找到的是「結構上最中心的節點」，不一定等於「他最該先解的那一個」。
5. 一次只解一條：選定核心後，只對那一條往下跑六問；其餘之後再迭代。先解核心，不要一次全做。

需求本來就夠聚焦（單一工作流）→ 跳過這步，直接六問。

## 固定順序（對第 0 步選定的那條核心跑；需求本來就聚焦，直接從這裡開始）

先問核心三問——通常問完，雛形就長出來：
1. 角色：這個人／單位站在整條流程哪一節？誰餵他資料、他餵誰？把他拿掉，哪裡會斷？要弄壞整條流程，插拔誰最有效？（這一問常問出「真正的瓶頸是入口，不是工具」）
2. 事件：每天一定會發生什麼？只有異常才發生什麼？一年才幾次的是什麼？（系統不是由畫面組成，是由事件組成）
3. 資料流：資料哪裡來、誰給、多久更新／失效？幫他寫出「沒有 A 就沒有 B」的因果鏈，一路到錢或帳為止。（事件決定資料、資料決定功能）

雛形有了、但覺得還不夠準或不夠穩時，再問精修三問：
4. 責任：出錯誰被罰、誰被告、誰簽名？（決定：最後一關一定要人簽）
5. 異常：哪裡會錯？誰先發現？發現了怎麼補？（99% 的系統死在這）
6. 檢查＋回歸：哪一步只能人做？哪一步 AI 做但人要簽？成果怎麼驗、錯了怎麼回歸、這次判斷存哪、下次自動被用到？（AI 只出現在這一問＝當分析師，不當決策者）

## 收尾（所有問題問完後）
綜合成結構：這個需求會長出哪些模組、哪一步一定要人簽、哪裡最容易壞；最後才問這些模組要不要做成規則檔／自動化／系統。順序是單向的：角色 → 事件 → 資料 → 功能，反推不動。這就是軟體界的「事件風暴（EventStorming）」。
'@

